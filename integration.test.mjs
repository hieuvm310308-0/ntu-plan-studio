import assert from 'node:assert/strict';
import {catalog,catalogMetadata,initialSelections} from './dist/catalog.js';
import {upgradeState} from './dist/state.js';
import {parseCatalogJSON,parseImportText} from './dist/import.js';
import {conflicts,solve} from './dist/engine.js';
const restored=parseCatalogJSON(JSON.stringify(catalog));
assert.equal(restored.length,catalogMetadata.moduleCount);
assert.equal(initialSelections.length,0);
assert.ok(catalog.length>70);
assert.equal(catalog.flatMap(m=>m.indexes).length,catalogMetadata.indexCount);
assert.equal(catalog.flatMap(m=>m.indexes.flatMap(i=>i.sessions)).length,catalogMetadata.sessionCount);
for(const m of catalog){assert.equal(m.sample,false);for(const i of m.indexes)assert.match(i.id,/^\d{5}$/)}
const chosen=['SC1001','SC1004','SC1005'].map(code=>({...restored.find(m=>m.code===code),locked:false}));
const blocks=[{day:0,start:0,end:480}];
const options=solve(chosen,blocks,{maxResults:6});
assert.ok(options.solutions.length);
assert.equal(solve(chosen,[{day:0,start:0,end:600}]).solutions.length,0,'No index can move a mandatory Monday morning lecture');
for(const option of options.solutions){assert.equal(conflicts(chosen.flatMap(m=>m.indexes.find(i=>i.id===option.selections[m.code]).sessions),blocks).length,0)}
assert.equal(parseImportText('SC1001 10001',catalog).matches[0].indexId,'10001');
const sc1001=catalog.find(m=>m.code==='SC1001').indexes.find(i=>i.id==='10001');
assert.equal(sc1001.sessions.length,4);
assert.deepEqual(sc1001.sessions[0],{day:0,start:570,end:620,type:'LEC/STUDIO',group:'LE1',venue:'LT19A',remark:''});
assert.ok(catalog.find(m=>m.code==='HY0001').indexes.some(i=>i.sessions.some(s=>s.day===5)));
const imported={code:'SC9999',title:'Imported module',au:0,indexes:[{id:'IMPORTED-abcdef',sessions:[{day:0,start:600,end:660}]}]};
assert.equal(parseCatalogJSON(JSON.stringify([imported]))[0].au,0);
const saved={catalog:[...catalog,{code:'SC9998',title:'Legacy demo',au:3,sample:true,indexes:[{id:'DEMO-99998',sessions:[{day:0,start:600,end:660}]}]}],active:'p',plans:[{id:'p',modules:[{code:'SC1001',selected:'10001',locked:true},{code:'SC9998',selected:'DEMO-99998'}],blocks:[{day:0,start:0,end:540}]}]};
const migrated=upgradeState(saved,catalog,catalogMetadata);
assert.equal(migrated.removed,1);assert.equal(migrated.state.plans[0].modules.length,1);
assert.equal(migrated.state.plans[0].modules[0].locked,true);assert.equal(migrated.state.plans[0].blocks.length,1);
assert.equal(saved.plans[0].modules.length,2);
const manualState={...saved,catalog:[...catalog,imported],plans:[{id:'p',modules:[{code:'SC9999',selected:'IMPORTED-abcdef'}],blocks:[]}]};
assert.equal(upgradeState(manualState,catalog,catalogMetadata).state.plans[0].modules.length,1);
const userOverride={code:'SC1001',title:'User timetable',au:2,sample:false,indexes:[{id:'89999',sessions:[{day:1,start:600,end:660}]}]};
const overrideState={...saved,catalog:[userOverride],plans:[{id:'p',modules:[{code:'SC1001',selected:'89999'}],blocks:[]}]};
assert.equal(upgradeState(overrideState,catalog,catalogMetadata).state.plans[0].modules[0].selected,'89999','Explicit legacy user imports are kept');
console.log('Official catalog, complete index rows, weekend sessions, solver and plan migration checks passed.');
